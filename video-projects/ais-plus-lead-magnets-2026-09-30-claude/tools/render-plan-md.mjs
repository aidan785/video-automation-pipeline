#!/usr/bin/env node
// 04-edit-plan/*.plan.json -> 04-edit-plan/EDIT-PLAN.md (human review) + vsl-assembly.json
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const P = (s) => JSON.parse(readFileSync(join(ROOT, "04-edit-plan", `${s}.plan.json`), "utf8"));
const mmss = (t) => `${Math.floor(t / 60)}:${(t % 60).toFixed(2).padStart(5, "0")}`;
const JOIN_BREATH = 0.0; // intros already end with a 0.5s tail pad; core starts with a 0.2s head pad

const clips = ["01-ad-sop", "02-ad-aios", "03-ad-scrollcraft", "04-vsl-intro-sop", "05-vsl-intro-aios", "06-vsl-intro-scrollcraft", "07-vsl-intro-generic", "08-vsl-core"];
const plans = Object.fromEntries(clips.map((c) => [c, P(c)]));
const core = plans["08-vsl-core"];
const bridge = core.markers.find((m) => m.id === "PROOF_BRIDGE");
const bridgeEdit = bridge.editTime;
const coreDur = core.proposedDuration;

const versions = [
  { out: "04 VSL - First AI Client SOP", intro: "04-vsl-intro-sop", coreFrom: 0 },
  { out: "05 VSL - AI OS Template", intro: "05-vsl-intro-aios", coreFrom: 0 },
  { out: "06 VSL - Scrollcraft", intro: "06-vsl-intro-scrollcraft", coreFrom: 0 },
  { out: "07 VSL - Generic (free Skool join emails)", intro: "07-vsl-intro-generic", coreFrom: bridgeEdit },
].map((v) => {
  const introDur = plans[v.intro].proposedDuration;
  const coreLen = coreDur - v.coreFrom;
  return { ...v, introDur, coreSection: v.coreFrom === 0 ? "full core (opening + proof bridge onward)" : "core from PROOF_BRIDGE", coreIn: v.coreFrom, joinAt: introDur, total: +(introDur + JOIN_BREATH + coreLen).toFixed(2) };
});
writeFileSync(join(ROOT, "04-edit-plan", "vsl-assembly.json"), JSON.stringify({ coreDuration: coreDur, proofBridge: { raw: bridge.raw, coreEditTime: bridgeEdit }, versions }, null, 2) + "\n");

let md = `# Edit plan (proposed, Checkpoint 1)

Generated by \`tools/render-plan-md.mjs\` from \`04-edit-plan/*.plan.json\`. Nothing has been cut or rendered yet.
All times are RAW source times unless marked "edit". Retake cuts are anchored on transcript words, not on the brief's rough timestamps.

**Pause policy:** any gap over ${core.policy.maxGap}s between kept words becomes a breath of ${core.policy.tailPad}s after the last word + ${core.policy.leadPad}s before the next onset.
Head pad ${core.policy.headPad}s, end pad ${core.policy.endPad}s. Every join gets an ear/RMS check at build time (Scribe word ends sit on the last voiced sample).

## Durations

| Clip | Raw | Proposed clean | Retake cuts | Pauses trimmed | Pause time removed |
| --- | --- | --- | --- | --- | --- |
${clips.map((c) => { const p = plans[c]; return `| ${c} | ${mmss(p.rawDuration)} | **${mmss(p.proposedDuration)}** | ${p.retakeCuts.length} | ${p.pauseTrims.length} | ${p.pauseTrims.reduce((s, x) => s + x.removedSec, 0).toFixed(1)}s |`; }).join("\n")}

## VSL assembly (core built once, reused)

Proof bridge marker: raw **${bridge.raw}** ("So this page is full of examples...") = core edit **${mmss(bridgeEdit)}**.

| Version | Intro | Core section | Join at (edit) | Est. total |
| --- | --- | --- | --- | --- |
${versions.map((v) => `| ${v.out} | ${v.intro} (${mmss(v.introDur)}) | ${v.coreSection}${v.coreIn ? ` (core ${mmss(v.coreIn)} to end)` : ""} | ${mmss(v.joinAt)} | **${mmss(v.total)}** |`).join("\n")}

`;

for (const c of clips) {
  const p = plans[c];
  md += `## ${c}\n\n`;
  if (p.retakeCuts.length) {
    md += `**Retake cuts (last take kept):**\n\n| ID | Removed from | Kept take starts | Removed text | Why |\n| --- | --- | --- | --- | --- |\n`;
    md += p.retakeCuts.map((r) => `| ${r.id} | ${r.firstRemovedWord} | ${r.keptTakeStarts} | ${r.removedText.length > 90 ? r.removedText.slice(0, 90) + "..." : r.removedText} | ${r.why} |`).join("\n") + "\n\n";
  } else md += `**Retake cuts:** none needed (single clean take).\n\n`;
  if (p.optional.length) md += `**Optional, decided by ear:**\n${p.optional.map((o) => `- ${o.id}: ${o.note}`).join("\n")}\n\n`;
  if (p.markers.length) md += `**Markers:**\n${p.markers.map((m) => `- ${m.id}: raw ${m.raw} -> edit ${mmss(m.editTime)}. ${m.note}`).join("\n")}\n\n`;
  md += `**Pause trims:** ${p.pauseTrims.map((x) => `${x.at} (${x.rawGapSec}s)`).join(", ") || "none"}\n\n`;
  md += `<details><summary>Source to edit map (${p.keepSegments.length} keep segments)</summary>\n\n| Seg | Source in | Source out | Edit in | Edit out |\n| --- | --- | --- | --- | --- |\n`;
  md += p.keepSegments.map((s) => `| ${s.seg} | ${mmss(s.srcIn)} | ${mmss(s.srcOut)} | ${mmss(s.editIn)} | ${mmss(s.editOut)} |`).join("\n") + "\n\n</details>\n\n";
}
writeFileSync(join(ROOT, "04-edit-plan", "EDIT-PLAN.md"), md);
console.table(versions.map((v) => ({ version: v.out, total: mmss(v.total), joinAt: mmss(v.joinAt) })));
